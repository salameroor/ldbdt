export const DONATION_GAP_DAYS = 90

const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯']

export function toBn(value: number | string) {
  return String(value).replace(/\d/g, (d) => BN_DIGITS[Number(d)])
}

export function formatBnDate(value: string | Date | null) {
  if (!value) return '—'
  const d = typeof value === 'string' ? new Date(value) : value
  return new Intl.DateTimeFormat('bn-BD', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(d)
}

export function formatBnDateTime(value: Date) {
  return new Intl.DateTimeFormat('bn-BD', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  }).format(value)
}

export function isReadyToDonate(lastDonationDate: string | null, available: boolean) {
  if (!available) return false
  if (!lastDonationDate) return true
  const days = (Date.now() - new Date(lastDonationDate).getTime()) / 86_400_000
  return days >= DONATION_GAP_DAYS
}

